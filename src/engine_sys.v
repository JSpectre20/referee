 * engine_sys: the engine subsystem, two engines (docs/isa-timing.md 0b, diffs 17-20).
 *
 *   - 2-flop synchronizers for engine inputs 0..11 (uio_in[0..7], ui_in[0..3]),
 *     shared by both engines
 *   - judge-channel mux: channel ch = ui_in[4+ch] (default, input-only pads:
 *     non-intrusive) or uio_in[0..7] (global config word 6). A channel on
 *     uio_in can watch a pin the other engine drives: the Referee judging the
 *     bus the Player speaks
 *   - edge_ts, 4 channels, 16-bit timestamps; engine inputs 12..15 of BOTH
 *     engines are its synchronized levels, so WAITP and the timestamps see the
 *     same signal. Only the Referee snapshots timestamps, and only its RUN
 *     clears edge_ts's `missed`
 *   - the global config (8 words; written only while BOTH engines are halted)
 *     and its decode: per output pin owner (none / engine 0 / engine 1) + mode
 *   - engine 0, the Referee (64 words, all referee hardware), and engine 1,
 *     the Player (96 words, no referee hardware): one module, two parameter sets
 *   - the pad drivers: each pin follows the engine that owns it. Push-pull
 *     drives the value; open-drain drives 0 or releases (oe = 0); unowned pins
 *     are not driven. A pin is driven only once its owner has had a RUN start
 *     since reset (0b, diff 16, per engine: diff 20), whatever the config says.
 *     One owner per pin, and RUN(e) refuses claims of pins e doesn't own, so
 *     two engines can never drive one pin (A17).
 *
 * Host side: one command at a time addresses one engine, named by h_e. The
 * per-engine strobes go to engine h_e and the per-engine read data comes from
 * it. The verdict, stats and LOST ports exist only on the Referee and go
 * straight to engine 0 (the host port NAKs them for e = 1; the drain pops
 * during a reply, when h_e may already show the next packet's bytes).
 *
 * Output pins: 0..7 = uio[0..7]; 8..14 = uo_out[0,1,2,3,5,6,7]. uo_out[4] is
 * the host UART TX and is never driven from here.
 */

`default_nettype none

module engine_sys (
    input  wire        clk,
    input  wire        rst_n,

    input  wire [ 7:0] ui_in,
    input  wire [ 7:0] uio_in,
    output wire [ 7:0] uio_out,
    output wire [ 7:0] uio_oe,
    output wire [ 7:0] uo_eng,   // engine-driven uo_out bits (bit 4 always 0)

    // host: global image
    input  wire        h_gwe,
    input  wire [ 2:0] h_gaddr,
    input  wire [15:0] h_gwdata,
    output wire [15:0] h_grdata,
    input  wire        h_gcrc_we,
    input  wire [15:0] h_gcrc,

    // host: the engine this command addresses (0 Referee, 1 Player)
    input  wire        h_e,
    // host: per-engine strobes (go to engine h_e) and read data (from engine h_e);
    // see engine.v
    input  wire        h_we,
    input  wire [ 6:0] h_addr,
    input  wire [15:0] h_wdata,
    input  wire [ 6:0] h_raddr,
    output wire [15:0] h_rdata,
    input  wire        h_crc_we,
    input  wire [15:0] h_crc,
    input  wire        h_run,
    input  wire        h_halt,
    input  wire        h_in_push,
    input  wire [ 7:0] h_in_data,
    output wire        in_full,
    input  wire        h_out_pop,
    output wire [ 7:0] out_data,
    output wire        out_empty,
    input  wire        h_status_clear,
    output wire [15:0] crc_got_g,
    output wire [15:0] crc_got_e,
    output wire [ 7:0] status,
    // per engine, bit e = engine e
    output wire [ 1:0] halted,
    output wire [ 1:0] running,
    output wire [ 1:0] checking,
    // host: Referee only (engine 0)
    input  wire        h_vf_pop,
    output wire [15:0] vf_data,
    output wire [ 3:0] vf_count,
    input  wire        h_stats_latch,
    input  wire [ 1:0] h_stats_slot,
    input  wire [ 2:0] h_stats_idx,
    output wire [15:0] stats_rdata,
    input  wire        h_stats_clear,
    input  wire        h_lost_clear,
    output wire [ 7:0] lost,
    output wire        ni
);

  // BEGIN GENERATED by tools/isagen.py from isa.yaml -- do not edit
  localparam integer REFEREE_PROG_WORDS = 64;  // engine 0
  localparam integer PLAYER_PROG_WORDS = 96;  // engine 1
  // END GENERATED

  // ---------------------------------------------------------------------------
  // Time base: free-running cycle counter shared by edge_ts and the engine
  // ---------------------------------------------------------------------------
  reg [15:0] now;
  always @(posedge clk) begin
    if (!rst_n) now <= 16'd0;
    else now <= now + 16'd1;
  end

  // ---------------------------------------------------------------------------
  // Global config
  // ---------------------------------------------------------------------------
  // The config is shared, so it may change only while BOTH engines are
  // halted: a running engine's pins, and a checking engine's CRC, depend on it.
  wire all_halted = &halted;
  reg [15:0] glob[0:7];
  integer gi;
  always @(posedge clk) begin
    if (!rst_n) begin
      for (gi = 0; gi < 8; gi = gi + 1) glob[gi] <= 16'd0;  // all pins unowned, mux = ui_in
`ifdef ENGINE_FORMAL_START_RUNNING
      // formal reachability tasks only (see engine.v): uio[0..3] owned by
      // engine 0 and uio[4..7] by engine 1, all open-drain, so the pad covers
      // are reachable without a RUN check
      glob[2] <= 16'h6666;
      glob[3] <= 16'hAAAA;
`endif
    end else if (h_gwe && all_halted) begin
      glob[h_gaddr] <= h_gwdata;
    end
  end
  reg [15:0] g_crc_exp;
  always @(posedge clk) begin
`ifdef ENGINE_FORMAL_START_RUNNING
    if (!rst_n) g_crc_exp <= 16'hFFFF;  // = crc_got_g: as after a passed check (formal only)
`else
    if (!rst_n) g_crc_exp <= 16'd0;
`endif
    else if (h_gcrc_we && all_halted) g_crc_exp <= h_gcrc;  // only while halted, like the config
  end
  assign h_grdata = glob[h_gaddr];
  // each engine reads the config through its own port during its RUN check
  // (the host port runs one check at a time, but nothing here relies on that)
  wire [2:0] gw_addr0, gw_addr1;
  wire [15:0] gw_data0 = glob[gw_addr0];
  wire [15:0] gw_data1 = glob[gw_addr1];

  // per output pin: owner (2 bits) and mode (2 bits), 4 pins per word (words 2..5).
  // owner 0 = none, 1 = engine 0, 2 = engine 1, 3 = none (reserved)
  wire [63:0] pin_nib = {glob[5], glob[4], glob[3], glob[2]};
  wire [14:0] owned0, owned1;
  wire [ 7:0] od_mode;
  wire [14:0] pp_mode;
  genvar p;
  generate
    for (p = 0; p < 15; p = p + 1) begin : g_pin
      wire [1:0] owner = pin_nib[4*p+2+:2];
      wire [1:0] mode = pin_nib[4*p+:2];
      // engine e (owner code e + 1) may drive pin p if it owns it in a driving
      // mode; uo_out pins (8..14) are push-pull only. One owner code per pin:
      // owned0 and owned1 are disjoint by construction.
      wire drv = (mode != 2'd0) && ((p < 8) || (mode == 2'd1));
      assign owned0[p] = (owner == 2'd1) && drv;
      assign owned1[p] = (owner == 2'd2) && drv;
      assign pp_mode[p] = (mode == 2'd1);
      if (p < 8) begin : g_od
        assign od_mode[p] = (mode == 2'd2);
      end
    end
  endgenerate

  // judge-channel mux (word 6): 0 = ui_in[4+ch], 1..8 = uio_in[0..7]
  wire [3:0] ch_raw;
  wire [3:0] ch_src_is_ui;
  generate
    for (p = 0; p < 4; p = p + 1) begin : g_mux
      wire [3:0] src = glob[6][4*p+:4];
      assign ch_raw[p] = (src == 4'd0) ? ui_in[4+p] : uio_in[src[2:0] - 3'd1];
      assign ch_src_is_ui[p] = (src == 4'd0);
    end
  endgenerate
  assign ni = &ch_src_is_ui;

  // ---------------------------------------------------------------------------
  // Synchronizers for engine inputs 0..11
  // ---------------------------------------------------------------------------
  reg [11:0] sync1, sync2;
  always @(posedge clk) begin
    if (!rst_n) begin
      sync1 <= 12'd0;
      sync2 <= 12'd0;
    end else begin
      sync1 <= {ui_in[3:0], uio_in};
      sync2 <= sync1;
    end
  end

  // ---------------------------------------------------------------------------
  // edge_ts
  // ---------------------------------------------------------------------------
  wire [3:0] et_rise, et_fall, et_level, et_toggled, et_rise_stale, et_fall_stale, et_missed, et_last_fall;
  wire [63:0] et_rise_ts, et_fall_ts;
  wire et_clear_missed;
  edge_ts #(
      .N(4), .TS_W(16)
  ) u_edge (
      .clk(clk), .rst_n(rst_n), .pins(ch_raw), .now(now), .clear({4{et_clear_missed}}),
      .level(et_level), .rise(et_rise), .fall(et_fall),
      .rise_ts(et_rise_ts), .fall_ts(et_fall_ts), .toggled(et_toggled),
      .rise_stale(et_rise_stale), .fall_stale(et_fall_stale), .missed(et_missed),
      .last_fall(et_last_fall)
  );

  // ---------------------------------------------------------------------------
  // The two engines
  // ---------------------------------------------------------------------------
  // Host strobes go to the engine the command names (h_e); read data comes
  // from it. Only one command executes per cycle, so one h_e suffices.
  wire e0 = !h_e, e1 = h_e;
  wire [14:0] out_val0, out_val1;
  wire [15:0] h_rdata0, h_rdata1, crc_got_g0, crc_got_g1, crc_got_e0, crc_got_e1;
  wire [7:0] out_data0, out_data1, status0, status1, lost1;
  wire in_full0, in_full1, out_empty0, out_empty1, run_start0, run_start1;
  wire [15:0] vf_data1, stats_rdata1;
  wire [3:0] vf_count1;
  wire et_clear_missed1;
`ifdef FORMAL
  wire [14:0] f_drive0, f_drive1;
  wire f_halting0, f_halting1;
`endif

  // engine 0: the Referee
  engine #(
      .REFEREE(1), .PROG_WORDS(REFEREE_PROG_WORDS)
  ) u_eng0 (
      .clk(clk), .rst_n(rst_n), .now(now),
      .in_sync({et_level, sync2}),
      .et_rise(et_rise), .et_fall(et_fall), .et_rise_ts(et_rise_ts), .et_fall_ts(et_fall_ts),
      .et_rise_stale(et_rise_stale), .et_fall_stale(et_fall_stale), .et_missed(et_missed),
      .et_last_fall(et_last_fall), .et_clear_missed(et_clear_missed), .run_start(run_start0),
      .owned(owned0), .od_mode(od_mode), .ni(ni),
      .gw_addr(gw_addr0), .gw_data(gw_data0), .g_crc_exp(g_crc_exp),
      .out_val(out_val0),
      .h_we(h_we && e0), .h_addr(h_addr), .h_wdata(h_wdata), .h_raddr(h_raddr), .h_rdata(h_rdata0),
      .h_crc_we(h_crc_we && e0), .h_crc(h_crc), .h_run(h_run && e0), .h_halt(h_halt && e0),
      .h_in_push(h_in_push && e0), .h_in_data(h_in_data), .in_full(in_full0),
      .h_out_pop(h_out_pop && e0), .out_data(out_data0), .out_empty(out_empty0),
      .h_vf_pop(h_vf_pop), .vf_data(vf_data), .vf_count(vf_count),
      .h_stats_latch(h_stats_latch), .h_stats_slot(h_stats_slot), .h_stats_idx(h_stats_idx),
      .stats_rdata(stats_rdata), .h_stats_clear(h_stats_clear),
      .h_lost_clear(h_lost_clear), .lost(lost), .h_status_clear(h_status_clear && e0),
      .halted(halted[0]), .running(running[0]), .checking(checking[0]),
      .crc_got_g(crc_got_g0), .crc_got_e(crc_got_e0), .status(status0)
`ifdef FORMAL
      , .f_drive(f_drive0), .f_halting(f_halting0)
`endif
  );

  // engine 1: the Player (no snapshot, verdict, bounds, stats or VERDICT FIFO;
  // its verdict / stats / LOST ports are tied off inside and left open here)
  engine #(
      .REFEREE(0), .PROG_WORDS(PLAYER_PROG_WORDS)
  ) u_eng1 (
      .clk(clk), .rst_n(rst_n), .now(now),
      .in_sync({et_level, sync2}),
      .et_rise(et_rise), .et_fall(et_fall), .et_rise_ts(et_rise_ts), .et_fall_ts(et_fall_ts),
      .et_rise_stale(et_rise_stale), .et_fall_stale(et_fall_stale), .et_missed(et_missed),
      .et_last_fall(et_last_fall), .et_clear_missed(et_clear_missed1), .run_start(run_start1),
      .owned(owned1), .od_mode(od_mode), .ni(ni),
      .gw_addr(gw_addr1), .gw_data(gw_data1), .g_crc_exp(g_crc_exp),
      .out_val(out_val1),
      .h_we(h_we && e1), .h_addr(h_addr), .h_wdata(h_wdata), .h_raddr(h_raddr), .h_rdata(h_rdata1),
      .h_crc_we(h_crc_we && e1), .h_crc(h_crc), .h_run(h_run && e1), .h_halt(h_halt && e1),
      .h_in_push(h_in_push && e1), .h_in_data(h_in_data), .in_full(in_full1),
      .h_out_pop(h_out_pop && e1), .out_data(out_data1), .out_empty(out_empty1),
      .h_vf_pop(1'b0), .vf_data(vf_data1), .vf_count(vf_count1),
      .h_stats_latch(1'b0), .h_stats_slot(2'd0), .h_stats_idx(3'd0),
      .stats_rdata(stats_rdata1), .h_stats_clear(1'b0),
      .h_lost_clear(1'b0), .lost(lost1), .h_status_clear(h_status_clear && e1),
      .halted(halted[1]), .running(running[1]), .checking(checking[1]),
      .crc_got_g(crc_got_g1), .crc_got_e(crc_got_e1), .status(status1)
`ifdef FORMAL
      , .f_drive(f_drive1), .f_halting(f_halting1)
`endif
  );

  assign h_rdata = e1 ? h_rdata1 : h_rdata0;
  assign in_full = e1 ? in_full1 : in_full0;
  assign out_data = e1 ? out_data1 : out_data0;
  assign out_empty = e1 ? out_empty1 : out_empty0;
  assign crc_got_g = e1 ? crc_got_g1 : crc_got_g0;
  assign crc_got_e = e1 ? crc_got_e1 : crc_got_e0;
  assign status = e1 ? status1 : status0;

  // ---------------------------------------------------------------------------
  // Pads
  // ---------------------------------------------------------------------------
  // Nothing is driven before the first RUN (docs/isa-timing.md 0b, diff 16):
  // the host writes the global config while loading, before any image has
  // passed its check, and a pin must not start driving a bus just because the
  // config names an owner. Per engine (0b, diff 20): ran[e] is set by engine
  // e's first RUN start since reset and only a reset clears it; from then on
  // the config's ownership applies to e's pins (a halted engine keeps its
  // push-pull levels, as the ISA says). A Referee RUN does not start driving
  // the Player's pins, and the other way round.
  reg [1:0] ran;
  always @(posedge clk) begin
`ifdef ENGINE_FORMAL_START_RUNNING
    if (!rst_n) ran <= 2'b11;  // formal fast start = the state after a passed RUN
`else
    if (!rst_n) ran <= 2'b00;
`endif
    else begin
      if (run_start0) ran[0] <= 1'b1;
      if (run_start1) ran[1] <= 1'b1;
    end
  end
  wire [14:0] drive = (ran[0] ? owned0 : 15'd0) | (ran[1] ? owned1 : 15'd0);
  // each pin shows its owner's value (for an unowned pin it doesn't matter)
  wire [14:0] val = (owned1 & out_val1) | (~owned1 & out_val0);

  generate
    for (p = 0; p < 8; p = p + 1) begin : g_uio
      // push-pull: drive the value; open-drain: drive 0 when the value is 0, else release
      assign uio_oe[p] = drive[p] && (pp_mode[p] || !val[p]);
      assign uio_out[p] = drive[p] && pp_mode[p] && val[p];
    end
  endgenerate
  // pins 8..14 -> uo_out[0,1,2,3,5,6,7]
  assign uo_eng = {
    drive[14] & val[14], drive[13] & val[13], drive[12] & val[12], 1'b0,
    drive[11] & val[11], drive[10] & val[10], drive[9] & val[9], drive[8] & val[8]
  };

  // pin 15 is reserved; the Player's verdict / stats / LOST outputs are constant 0
  wire _unused = &{1'b0, et_toggled, pp_mode[14:8], pin_nib[63:60], et_clear_missed1,
                   vf_data1, vf_count1, stats_rdata1, lost1};

`ifdef FORMAL
  // ===========================================================================
  // Pad and global-config properties (docs/isa-timing.md section 9), proved by
  // formal/engine.sby together with the engine's own (src/engine.v).
  // ===========================================================================
  reg f_past;  // the last cycle was out of reset
  always @(posedge clk) f_past <= rst_n;

  (* anyconst *) reg [2:0] f_gidx;  // any global config word
  integer fp;

  always @(posedge clk) begin
    if (rst_n && f_past) begin
      // the global config (pin owners and modes, channel mux) changes only by a
      // host write while BOTH engines are halted
      if (glob[f_gidx] != $past(glob[f_gidx])) assert ($past(h_gwe && all_halted && h_gaddr == f_gidx));
      if (g_crc_exp != $past(g_crc_exp)) assert ($past(h_gcrc_we && all_halted));
      // from either engine's RUN until it runs or its check fails (and while it
      // runs), the global config and its expected CRC are constant
      if (!$past(all_halted)) assert (glob[f_gidx] == $past(glob[f_gidx]) && g_crc_exp == $past(g_crc_exp));

      // -- one owner per pin: the two engines' pin sets are disjoint
      assert ((owned0 & owned1) == 15'd0);

      // -- pads change only one cycle after a SET / SHO of the pin's owner, and
      //    only for owned pins (checked over a stretch where the owner runs
      //    throughout; while both are halted, the host may change the config)
      for (fp = 0; fp < 15; fp = fp + 1) begin
        if (f_pin_pad(fp, uio_oe, uio_out, uo_eng) != f_pin_pad(fp, $past(uio_oe), $past(uio_out), $past(uo_eng))) begin
          if (owned0[fp] && $past(running[0]) && running[0]) assert ($past(f_drive0[fp]));
          if (owned1[fp] && $past(running[1]) && running[1]) assert ($past(f_drive1[fp]));
          // a pin owned by neither never changes while an engine runs (the
          // config is frozen then)
          if (!owned0[fp] && !owned1[fp]) assert ($past(all_halted));
        end
      end
      // an unowned pin is never driven, and uo_out[4] (host TX) never by an engine
      for (fp = 0; fp < 8; fp = fp + 1) if (!owned0[fp] && !owned1[fp]) assert (!uio_oe[fp] && !uio_out[fp]);
      assert (!uo_eng[4]);
      // -- before engine e's first RUN since reset none of its pins is driven,
      //    and only its own RUN start ends that
      for (fp = 0; fp < 8; fp = fp + 1) begin
        if (owned0[fp] && !ran[0]) assert (!uio_oe[fp] && !uio_out[fp]);
        if (owned1[fp] && !ran[1]) assert (!uio_oe[fp] && !uio_out[fp]);
      end
      for (fp = 8; fp < 15; fp = fp + 1)
        if ((owned0[fp] && !ran[0]) || (owned1[fp] && !ran[1])) assert (!f_pin_pad(fp, uio_oe, uio_out, uo_eng));
      if (ran == 2'b00) assert (uio_oe == 8'd0 && uio_out == 8'd0 && uo_eng == 8'd0);
      if (ran[0] && !$past(ran[0])) assert ($past(run_start0));
      if (ran[1] && !$past(ran[1])) assert ($past(run_start1));
      if (running[0]) assert (ran[0]);
      if (running[1]) assert (ran[1]);
      // -- only the Referee's RUN clears edge_ts's `missed` (0b, diff 20)
      assert (et_clear_missed == run_start0);

      // -- HALT releases open-drain pins: after engine e halts, none of its
      //    open-drain pins pulls low
      for (fp = 0; fp < 8; fp = fp + 1) begin
        if ($past(f_halting0) && od_mode[fp] && owned0[fp]) assert (!uio_oe[fp]);
        if ($past(f_halting1) && od_mode[fp] && owned1[fp]) assert (!uio_oe[fp]);
      end
    end
  end

  // what output pin q presents: {oe, out} for uio pins, the value for uo_out pins
  function automatic [1:0] f_pin_pad(input integer q, input [7:0] oe, input [7:0] out, input [7:0] uo);
    begin
      if (q < 8) f_pin_pad = {oe[q], out[q]};
      else if (q < 12) f_pin_pad = {1'b0, uo[q-8]};
      else f_pin_pad = {1'b0, uo[q-7]};
    end
  endfunction

  always @(posedge clk) begin
    if (rst_n && f_past) begin
      cover ($past(running[0]) && running[0] && uio_oe[0] != $past(uio_oe[0]));  // a Referee open-drain pin pulled low / released
      cover ($past(running[1]) && running[1] && uio_oe[4] != $past(uio_oe[4]));  // the same for the Player
      cover ($past(f_halting0) && od_mode[1] && $past(uio_oe[1]));  // a halt releasing a held-low pin
      cover ($past(f_halting1) && od_mode[5] && $past(uio_oe[5]));
    end
  end
`endif

endmodule

`default_nettype wire
