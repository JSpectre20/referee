 * engine: one Referee engine (ISA v0.3, isa.yaml; contract in docs/isa-timing.md).
 *
 * Contains, per engine: the image (64-word program, 16-entry bounds table,
 * claimed-pin mask) in flip-flops, the registers and flags, the snapshot of
 * edge_ts with its trigger, JUDGE with the proved verdict rule and the stats,
 * the IN / OUT / VERDICT FIFOs, and the RUN check (CRC-16 over the global and
 * engine images plus the pin-claim check).
 *
 * Cycle semantics (identical to tools/refmodel.py, which the lockstep tests use):
 *   - An instruction issues when running, unless a WAITD is still holding the
 *     schedule: issue = running && !(wd_stall && NOW - DL < 0).
 *   - Every instruction takes 1 cycle; WAITP / WAITS stay at their pc until
 *     their event (T <- 0) or their timeout (T <- 1); the event wins a tie.
 *   - SET / SHO change out_val at the end of the cycle (pad at t+1).
 *   - Snapshot: a trigger reported in cycle r (while no snapshot is pending)
 *     is captured in cycle r+2 from the edge_ts registers, which then hold the
 *     state latched at the end of r+1. ORD marks edges latched in r-1..r+1.
 *   - RUN: the check reads 8 global + 97 engine words (105 cycles); on success
 *     the first instruction issues 106 cycles after the RUN strobe.
 */

`default_nettype none

module engine (
    input  wire        clk,
    input  wire        rst_n,
    input  wire [15:0] now,

    input  wire [15:0] in_sync,  // engine inputs 0..15, already synchronized

    // edge_ts, 4 channels (registered state + this cycle's report pulses)
    input  wire [ 3:0] et_rise,
    input  wire [ 3:0] et_fall,
    input  wire [63:0] et_rise_ts,
    input  wire [63:0] et_fall_ts,
    input  wire [ 3:0] et_rise_stale,
    input  wire [ 3:0] et_fall_stale,
    input  wire [ 3:0] et_missed,
    input  wire [ 3:0] et_last_fall,
    output wire        et_clear_missed,  // pulse when a RUN starts

    // global config (decoded by engine_sys)
    input  wire [14:0] owned,     // output pins this engine may drive
    input  wire [ 7:0] od_mode,   // uio pins in open-drain mode
    input  wire        ni,        // all judge channels on ui_in
    output wire [ 2:0] gw_addr,   // global image word read during the RUN check
    input  wire [15:0] gw_data,
    input  wire [15:0] g_crc_exp,

    output reg  [14:0] out_val,   // output pin values (pad = registered)

    // host side
    input  wire        h_we,
    input  wire [ 6:0] h_addr,
    input  wire [15:0] h_wdata,
    input  wire [ 6:0] h_raddr,
    output wire [15:0] h_rdata,
    input  wire        h_crc_we,
    input  wire [15:0] h_crc,
    input  wire        h_run,
    input  wire        h_halt,
    input  wire        h_in_push,
    input  wire [ 7:0] h_in_data,
    output wire        in_full,
    input  wire        h_out_pop,
    output wire [ 7:0] out_data,
    output wire        out_empty,
    input  wire        h_vf_pop,
    output wire [15:0] vf_data,
    output wire [ 3:0] vf_count,
    input  wire        h_stats_latch,
    input  wire [ 1:0] h_stats_slot,
    input  wire [ 2:0] h_stats_idx,
    output wire [15:0] stats_rdata,
    input  wire        h_stats_clear,
    input  wire        h_lost_clear,
    output reg  [ 7:0] lost,
    input  wire        h_status_clear,
    output wire        halted,
    output wire        running,
    output wire        checking,
    output reg  [15:0] crc_got_g,
    output reg  [15:0] crc_got_e,
    output wire [ 7:0] status
);

  // BEGIN GENERATED by tools/isagen.py from isa.yaml -- do not edit
  /* verilator lint_off UNUSEDPARAM */
  localparam [4:0] OP_NOP    = 5'h00;
  localparam [4:0] OP_HALT   = 5'h01;
  localparam [4:0] OP_SET    = 5'h02;
  localparam [4:0] OP_SHO    = 5'h03;
  localparam [4:0] OP_SHI    = 5'h04;
  localparam [4:0] OP_TSTP   = 5'h05;
  localparam [4:0] OP_MARK   = 5'h06;
  localparam [4:0] OP_TMO    = 5'h07;
  localparam [4:0] OP_WAITD  = 5'h08;
  localparam [4:0] OP_WAITP  = 5'h09;
  localparam [4:0] OP_WAITS  = 5'h0a;
  localparam [4:0] OP_JMP    = 5'h0b;
  localparam [4:0] OP_BR     = 5'h0c;
  localparam [4:0] OP_LOOP   = 5'h0d;
  localparam [4:0] OP_LDRC   = 5'h0e;
  localparam [4:0] OP_LDSR   = 5'h0f;
  localparam [4:0] OP_PULL   = 5'h10;
  localparam [4:0] OP_PUSH   = 5'h11;
  localparam [4:0] OP_TRIG   = 5'h12;
  localparam [4:0] OP_REL    = 5'h13;
  localparam [4:0] OP_TSGET  = 5'h14;
  localparam [4:0] OP_JUDGE  = 5'h15;
  localparam [4:0] OP_TMON   = 5'h16;
  localparam [4:0] OP_CMP    = 5'h17;
  localparam integer F_P_HI = 3, F_P_LO = 0;
  localparam integer F_Q_HI = 3, F_Q_LO = 0;
  localparam integer F_V_HI = 4, F_V_LO = 4;
  localparam integer F_MSB_HI = 4, F_MSB_LO = 4;
  localparam integer F_RAW_HI = 4, F_RAW_LO = 4;
  localparam integer F_PUSH_HI = 6, F_PUSH_LO = 5;
  localparam integer F_HI_HI = 8, F_HI_LO = 8;
  localparam integer F_N_HI = 10, F_N_LO = 0;
  localparam integer F_T_HI = 9, F_T_LO = 0;
  localparam integer F_X16_HI = 10, F_X16_LO = 10;
  localparam integer F_A_HI = 5, F_A_LO = 0;
  localparam integer F_C_HI = 8, F_C_LO = 6;
  localparam integer F_IMM_HI = 7, F_IMM_LO = 0;
  localparam integer F_R_HI = 5, F_R_LO = 5;
  localparam integer F_CH_HI = 1, F_CH_LO = 0;
  localparam integer F_E_HI = 3, F_E_LO = 2;
  localparam integer F_B_HI = 3, F_B_LO = 0;
  localparam [2:0] C_T = 3'd0;
  localparam [2:0] C_NT = 3'd1;
  localparam [2:0] C_C = 3'd2;
  localparam [2:0] C_NC = 3'd3;
  localparam [2:0] C_E = 3'd4;
  localparam [2:0] C_NE = 3'd5;
  localparam [2:0] C_S = 3'd6;
  localparam [2:0] C_NS = 3'd7;
  localparam [1:0] E_RISE = 2'd0;
  localparam [1:0] E_FALL = 2'd1;
  localparam [1:0] E_LAST = 2'd2;
  localparam [0:0] R_X = 1'd0;
  localparam [0:0] R_Y = 1'd1;
  localparam [1:0] PUSH_ALL = 2'd0;
  localparam [1:0] PUSH_NONPASS = 2'd1;
  localparam [1:0] PUSH_NONE = 2'd2;
  /* verilator lint_on UNUSEDPARAM */
  // END GENERATED

  localparam [1:0] ST_HALTED = 2'd0, ST_CHECK = 2'd1, ST_RUN = 2'd2;
  localparam [6:0] CHECK_LAST = 7'd104;  // 8 global + 97 engine words

  // ---------------------------------------------------------------------------
  // Image (flip-flops; contents undefined until loaded: the CRC check guards RUN)
  // ---------------------------------------------------------------------------
  reg [15:0] prog [0:63];
  reg [15:0] bnd  [0:31];
  reg [15:0] claims;

  reg [ 1:0] st;
  reg [ 6:0] chk_idx;
  reg [15:0] crc_exp_e;

  assign halted   = (st == ST_HALTED);
  assign running  = (st == ST_RUN);
  assign checking = (st == ST_CHECK);

  // One read port for the RUN check and host readback (both only when not running).
  wire [6:0] img_addr = checking ? (chk_idx - 7'd8) : h_raddr;
  reg  [15:0] img_word;
  always @(*) begin
    if (img_addr < 7'd64) img_word = prog[img_addr[5:0]];
    else if (img_addr < 7'd96) img_word = bnd[img_addr[4:0]];
    else img_word = claims;
  end
  assign h_rdata = img_word;
  assign gw_addr = chk_idx[2:0];

  always @(posedge clk) begin
    if (h_we && halted) begin
      if (h_addr < 7'd64) prog[h_addr[5:0]] <= h_wdata;
      else if (h_addr < 7'd96) bnd[h_addr[4:0]] <= h_wdata;
      else if (h_addr == 7'd96) claims <= h_wdata;
    end
  end

  // CRC-16/CCITT-FALSE, one 16-bit word per cycle (high byte first).
  function [15:0] crc16_word(input [15:0] crc_in, input [15:0] w);
    integer k;
    reg [15:0] c;
    begin
      c = crc_in;
      for (k = 15; k >= 0; k = k - 1) c = (c[15] ^ w[k]) ? ((c << 1) ^ 16'h1021) : (c << 1);
      crc16_word = c;
    end
  endfunction

  // ---------------------------------------------------------------------------
  // Registers
  // ---------------------------------------------------------------------------
  reg [5:0] pc;
  reg [15:0] X, Y, SR, DL, TO;
  reg [7:0] RC;
  reg T, C, E, S;
  reg wd_stall;
  reg FX, OX, FY, OY;
  reg [1:0] EX, EY;
  reg valid;
  reg [1:0] epoch;
  reg [1:0] cap_stage;
  reg trig_en, trig_e;
  reg [1:0] trig_ch;
  reg lost_since;
  reg out_ovf, vf_ovf, in_underrun, pin_fault, crc_fail;

  // snapshot
  reg [15:0] sn_rts[0:3], sn_fts[0:3];
  reg [3:0] sn_rstale, sn_fstale, sn_missed, sn_last, sn_ord_r, sn_ord_f;
  // report-pulse history: h1 = last cycle, h2 = 2 cycles ago, h3 = 3 cycles ago
  reg [3:0] h1_r, h1_f, h2_r, h2_f, h3_r, h3_f;

  assign status = {checking, running, S, crc_fail, pin_fault, in_underrun, vf_ovf, out_ovf};

  // ---------------------------------------------------------------------------
  // Decode
  // ---------------------------------------------------------------------------
  wire [15:0] instr = prog[pc];
  wire [ 4:0] op = instr[15:11];
  wire [ 3:0] f_p = instr[F_P_HI:F_P_LO];
  wire [ 3:0] f_q = instr[F_Q_HI:F_Q_LO];
  wire        f_v = instr[F_V_HI];
  wire        f_msb = instr[F_MSB_HI];
  wire        f_raw = instr[F_RAW_HI];
  wire [ 1:0] f_push = instr[F_PUSH_HI:F_PUSH_LO];
  wire        f_hi = instr[F_HI_HI];
  wire [10:0] f_n = instr[F_N_HI:F_N_LO];
  wire [ 9:0] f_t = instr[F_T_HI:F_T_LO];
  wire        f_x16 = instr[F_X16_HI];
  wire [ 5:0] f_a = instr[F_A_HI:F_A_LO];
  wire [ 2:0] f_c = instr[F_C_HI:F_C_LO];
  wire [ 7:0] f_imm = instr[F_IMM_HI:F_IMM_LO];
  wire        f_r = instr[F_R_HI];
  wire [ 1:0] f_ch = instr[F_CH_HI:F_CH_LO];
  wire [ 1:0] f_e = instr[F_E_HI:F_E_LO];
  wire [ 3:0] f_b = instr[F_B_HI:F_B_LO];

  wire        issue = running && !(wd_stall && $signed(now - DL) < 0);
  wire        in_bit = in_sync[f_q];
  wire        timed_out = $signed(now - TO) >= 0;
  wire [ 5:0] pc_inc = pc + 6'd1;
  wire [15:0] tval = f_x16 ? {2'b00, f_t, 4'b0000} : {6'd0, f_t};
  wire        pin_ok = (f_p != 4'd15) && owned[f_p];
  wire        sho_bit = f_msb ? SR[15] : SR[0];
  wire [ 7:0] sr_byte = f_hi ? SR[15:8] : SR[7:0];
  wire        br_flag = (f_c[2:1] == 2'd0) ? T : (f_c[2:1] == 2'd1) ? C : (f_c[2:1] == 2'd2) ? E : S;

  // TSGET source
  wire        ts_edge = (f_e == E_LAST) ? sn_last[f_ch] : f_e[0];
  wire [15:0] ts_val = ts_edge ? sn_fts[f_ch] : sn_rts[f_ch];
  wire        ts_f = (ts_edge ? sn_fstale[f_ch] : sn_rstale[f_ch]) | sn_missed[f_ch] | ~valid;
  wire        ts_o = ts_edge ? sn_ord_f[f_ch] : sn_ord_r[f_ch];

  // JUDGE
  wire [15:0] m = Y - X;
  wire        tagbad = (EX != EY);
  wire        invalid = FX | FY | OX | OY | tagbad;
  wire [15:0] b_hi = bnd[{f_b, 1'b0}];
  wire [15:0] b_lo = bnd[{f_b, 1'b1}];
  wire        v_pass, v_viol;
  verdict #(
      .M_W(16), .FRAC_W(4), .N_W(20), .U_FX(2 << 4), .SHARP(1)
  ) u_verdict (
      .m(m), .n_lo({b_hi, b_lo[15:12]}), .inexact(b_lo[11]), .is_max(b_lo[10]),
      .invalid(invalid), .pass(v_pass), .violation(v_viol)
  );
  wire [ 1:0] vcode = v_pass ? 2'd1 : v_viol ? 2'd2 : 2'd0;
  wire [ 2:0] msat = ($signed(m) < -16'sd4) ? 3'b100 : ($signed(m) > 16'sd3) ? 3'b011 : m[2:0];
  wire        do_push = (f_push == PUSH_ALL) || ((f_push == PUSH_NONPASS) && !v_pass);
  wire [15:0] vhdr = {vcode, FX, FY, tagbad, lost_since, ni, f_raw, f_b, (OX | OY), msat};

  // ---------------------------------------------------------------------------
  // FIFOs
  // ---------------------------------------------------------------------------
  reg [7:0] fin[0:3];
  reg [1:0] fin_rp, fin_wp;
  reg [2:0] fin_n;
  reg [7:0] fout[0:3];
  reg [1:0] fout_rp, fout_wp;
  reg [2:0] fout_n;
  reg [15:0] fv[0:7];
  reg [2:0] fv_rp, fv_wp;
  reg [3:0] fv_n;

  assign in_full = (fin_n == 3'd4);
  assign out_empty = (fout_n == 3'd0);
  assign out_data = fout[fout_rp];
  assign vf_data = fv[fv_rp];
  assign vf_count = fv_n;

  wire is_pull = issue && (op == OP_PULL);
  wire pull_ok = is_pull && (fin_n != 3'd0);
  wire host_in = h_in_push && !in_full;
  wire is_push = issue && (op == OP_PUSH);
  wire push_ok = is_push && (fout_n != 3'd4);
  wire host_out = h_out_pop && !out_empty;
  wire is_judge = issue && (op == OP_JUDGE);
  wire [3:0] vf_need = {3'd0, f_raw} + 4'd1;
  wire vf_room = (4'd8 - fv_n) >= vf_need;
  wire judge_push = is_judge && do_push && vf_room;
  wire host_v = h_vf_pop && (fv_n != 4'd0);

  // ---------------------------------------------------------------------------
  // Stats (slots 0..3)
  // ---------------------------------------------------------------------------
  reg [15:0] st_pass[0:3], st_viol[0:3], st_indet[0:3], st_min[0:3], st_max[0:3];
  reg [3:0] st_seen;
  reg [15:0] shadow[0:4];
  assign stats_rdata = (h_stats_idx <= 3'd4) ? shadow[h_stats_idx] : 16'd0;
  wire stats_upd = is_judge && (f_b[3:2] == 2'b00);

  // ---------------------------------------------------------------------------
  // Snapshot trigger
  // ---------------------------------------------------------------------------
  wire hit = running && trig_en && (trig_e ? et_fall[trig_ch] : et_rise[trig_ch]);
  wire busy = S || (cap_stage != 2'd0);
  wire lost_now = hit && busy;
  wire new_pending = hit && !busy;
  wire capture = (cap_stage == 2'd2);
  wire rel_now = issue && (op == OP_REL);

  // RUN check decision
  wire [15:0] crc_e_next = crc16_word(crc_got_e, img_word);
  wire [15:0] crc_g_next = crc16_word(crc_got_g, gw_data);
  wire check_last = checking && (chk_idx == CHECK_LAST);
  wire claims_ok = ((claims[14:0] & ~owned) == 15'd0) && !claims[15];
  wire check_ok = check_last && (crc_got_g == g_crc_exp) && (crc_e_next == crc_exp_e) && claims_ok;
  wire start = check_ok;
  assign et_clear_missed = start;

  integer i;

  always @(posedge clk) begin
    if (!rst_n) begin
      st <= ST_HALTED;
      chk_idx <= 7'd0;
      crc_exp_e <= 16'd0;
      crc_got_g <= 16'hFFFF;
      crc_got_e <= 16'hFFFF;
      crc_fail <= 1'b0;
      pc <= 6'd0;
      {X, Y, SR, DL, TO} <= 80'd0;
      RC <= 8'd0;
      {T, C, E, S, wd_stall, valid} <= 6'd0;
      {FX, OX, FY, OY} <= 4'd0;
      EX <= 2'd0;
      EY <= 2'd0;
      epoch <= 2'd0;
      cap_stage <= 2'd0;
      {trig_en, trig_e} <= 2'b00;
      trig_ch <= 2'd0;
      lost_since <= 1'b0;
      lost <= 8'd0;
      {out_ovf, vf_ovf, in_underrun, pin_fault} <= 4'd0;
      out_val <= {15{1'b1}};
      {sn_rstale, sn_fstale, sn_missed, sn_last, sn_ord_r, sn_ord_f} <= 24'd0;
      for (i = 0; i < 4; i = i + 1) begin
        sn_rts[i] <= 16'd0;
        sn_fts[i] <= 16'd0;
      end
      {h1_r, h1_f, h2_r, h2_f, h3_r, h3_f} <= 24'd0;
      {fin_rp, fin_wp, fout_rp, fout_wp} <= 8'd0;
      fin_n <= 3'd0;
      fout_n <= 3'd0;
      fv_rp <= 3'd0;
      fv_wp <= 3'd0;
      fv_n <= 4'd0;
      st_seen <= 4'd0;
      for (i = 0; i < 4; i = i + 1) begin
        st_pass[i] <= 16'd0;
        st_viol[i] <= 16'd0;
        st_indet[i] <= 16'd0;
        st_min[i] <= 16'd0;
        st_max[i] <= 16'd0;
      end
      for (i = 0; i < 5; i = i + 1) shadow[i] <= 16'd0;
    end else begin
      // ---- host: expected CRC, run, halt ---------------------------------
      if (h_crc_we) crc_exp_e <= h_crc;
      if (h_run && halted) begin
        st <= ST_CHECK;
        chk_idx <= 7'd0;
        crc_got_g <= 16'hFFFF;
        crc_got_e <= 16'hFFFF;
      end
      if (checking) begin
        if (chk_idx < 7'd8) crc_got_g <= crc_g_next;
        else crc_got_e <= crc_e_next;
        chk_idx <= chk_idx + 7'd1;
        if (check_last && !check_ok) begin
          st <= ST_HALTED;
          crc_fail <= 1'b1;
        end
        if (h_halt) st <= ST_HALTED;
      end

      // ---- execute ---------------------------------------------------------
      if (issue) begin
        wd_stall <= 1'b0;
        pc <= pc_inc;
        case (op)
          OP_HALT: begin
            pc <= pc;
            st <= ST_HALTED;
            for (i = 0; i < 8; i = i + 1) if (od_mode[i]) out_val[i] <= 1'b1;
          end
          OP_SET: if (pin_ok) out_val[f_p] <= f_v; else pin_fault <= 1'b1;
          OP_SHO: begin
            SR <= f_msb ? {SR[14:0], 1'b1} : {1'b1, SR[15:1]};
            if (pin_ok) out_val[f_p] <= sho_bit; else pin_fault <= 1'b1;
          end
          OP_SHI: begin
            C  <= in_bit;
            SR <= f_msb ? {SR[14:0], in_bit} : {in_bit, SR[15:1]};
          end
          OP_TSTP: C <= in_bit;
          OP_MARK: DL <= now;
          OP_TMO: TO <= DL + tval;
          OP_TMON: TO <= now + tval;
          OP_WAITD: begin
            DL <= DL + {5'd0, f_n};
            wd_stall <= 1'b1;
          end
          OP_WAITP, OP_WAITS: begin
            if ((op == OP_WAITP) ? (in_bit == f_v) : S) T <= 1'b0;
            else if (timed_out) T <= 1'b1;
            else pc <= pc;  // keep waiting
          end
          OP_JMP: pc <= f_a;
          OP_BR: if (br_flag ^ f_c[0]) pc <= f_a;
          OP_LOOP:
          if (RC != 8'd0) begin
            RC <= RC - 8'd1;
            pc <= f_a;
          end
          OP_LDRC: RC <= f_imm;
          OP_LDSR: if (f_hi) SR[15:8] <= f_imm; else SR[7:0] <= f_imm;
          OP_CMP: C <= (sr_byte == f_imm);
          OP_PULL:
          if (pull_ok) begin
            if (f_hi) SR[15:8] <= fin[fin_rp]; else SR[7:0] <= fin[fin_rp];
            E <= 1'b0;
          end else begin
            E <= 1'b1;
            in_underrun <= 1'b1;
          end
          OP_PUSH: if (!push_ok) out_ovf <= 1'b1;
          OP_TRIG: begin
            trig_en <= 1'b1;
            trig_ch <= f_ch;
            trig_e  <= f_e[0];
          end
          OP_TSGET:
          if (f_r) begin
            Y <= ts_val; FY <= ts_f; OY <= ts_o; EY <= epoch;
          end else begin
            X <= ts_val; FX <= ts_f; OX <= ts_o; EX <= epoch;
          end
          OP_JUDGE: if (do_push && !vf_room) vf_ovf <= 1'b1;
          default: ;  // NOP, REL (handled below), reserved opcodes
        endcase
      end

      // ---- stats -------------------------------------------------------------
      if (stats_upd) begin
        if (v_pass) st_pass[f_b[1:0]] <= (&st_pass[f_b[1:0]]) ? st_pass[f_b[1:0]] : st_pass[f_b[1:0]] + 16'd1;
        else if (v_viol) st_viol[f_b[1:0]] <= (&st_viol[f_b[1:0]]) ? st_viol[f_b[1:0]] : st_viol[f_b[1:0]] + 16'd1;
        else st_indet[f_b[1:0]] <= (&st_indet[f_b[1:0]]) ? st_indet[f_b[1:0]] : st_indet[f_b[1:0]] + 16'd1;
        if (!invalid) begin
          if (!st_seen[f_b[1:0]] || $signed(m) < $signed(st_min[f_b[1:0]])) st_min[f_b[1:0]] <= m;
          if (!st_seen[f_b[1:0]] || $signed(m) > $signed(st_max[f_b[1:0]])) st_max[f_b[1:0]] <= m;
          st_seen[f_b[1:0]] <= 1'b1;
        end
      end
      if (h_stats_latch) begin
        shadow[0] <= st_pass[h_stats_slot];
        shadow[1] <= st_viol[h_stats_slot];
        shadow[2] <= st_indet[h_stats_slot];
        shadow[3] <= st_min[h_stats_slot];
        shadow[4] <= st_max[h_stats_slot];
      end
      if (h_stats_clear) begin
        st_pass[h_stats_slot] <= 16'd0;
        st_viol[h_stats_slot] <= 16'd0;
        st_indet[h_stats_slot] <= 16'd0;
        st_min[h_stats_slot] <= 16'd0;
        st_max[h_stats_slot] <= 16'd0;
        st_seen[h_stats_slot] <= 1'b0;
      end

      // ---- FIFOs ---------------------------------------------------------------
      if (host_in) begin
        fin[fin_wp] <= h_in_data;
        fin_wp <= fin_wp + 2'd1;
      end
      if (pull_ok) fin_rp <= fin_rp + 2'd1;
      fin_n <= fin_n + {2'd0, host_in} - {2'd0, pull_ok};

      if (push_ok) begin
        fout[fout_wp] <= sr_byte;
        fout_wp <= fout_wp + 2'd1;
      end
      if (host_out) fout_rp <= fout_rp + 2'd1;
      fout_n <= fout_n + {2'd0, push_ok} - {2'd0, host_out};

      if (judge_push) begin
        fv[fv_wp] <= vhdr;
        if (f_raw) fv[fv_wp+3'd1] <= m;
        fv_wp <= fv_wp + vf_need[2:0];
      end
      if (host_v) fv_rp <= fv_rp + 3'd1;
      fv_n <= fv_n + (judge_push ? vf_need : 4'd0) - {3'd0, host_v};

      // ---- snapshot ------------------------------------------------------------
      if (capture) begin
        for (i = 0; i < 4; i = i + 1) begin
          sn_rts[i] <= et_rise_ts[i*16+:16];
          sn_fts[i] <= et_fall_ts[i*16+:16];
        end
        sn_rstale <= et_rise_stale;
        sn_fstale <= et_fall_stale;
        sn_missed <= et_missed;
        sn_last <= et_last_fall;
        sn_ord_r <= h1_r | h2_r | h3_r;
        sn_ord_f <= h1_f | h2_f | h3_f;
        epoch <= epoch + 2'd1;
        S <= 1'b1;
        valid <= 1'b1;
      end else if (rel_now) S <= 1'b0;
      cap_stage <= new_pending ? 2'd1 : (cap_stage == 2'd1) ? 2'd2 : 2'd0;
      if (lost_now) lost <= (&lost) ? lost : lost + 8'd1;
      if (lost_now) lost_since <= 1'b1;
      else if (is_judge) lost_since <= 1'b0;
      {h3_r, h3_f, h2_r, h2_f, h1_r, h1_f} <= {h2_r, h2_f, h1_r, h1_f, et_rise, et_fall};

      // ---- host clears win over same-cycle sets ----------------------------------
      if (h_status_clear) {out_ovf, vf_ovf, in_underrun, pin_fault, crc_fail} <= 5'd0;
      if (h_lost_clear) lost <= 8'd0;

      // ---- host halt ------------------------------------------------------------
      if (h_halt && running) begin
        st <= ST_HALTED;
        for (i = 0; i < 8; i = i + 1) if (od_mode[i]) out_val[i] <= 1'b1;
      end

      // ---- RUN starts (highest priority) ----------------------------------------
      if (start) begin
        st <= ST_RUN;
        crc_got_e <= crc_e_next;
        pc <= 6'd0;
        {X, Y, SR} <= 48'd0;
        RC <= 8'd0;
        DL <= now + 16'd1;
        TO <= now + 16'd1;
        {T, C, E, S, wd_stall, valid} <= 6'd0;
        {FX, OX, FY, OY} <= 4'd0;
        EX <= 2'd0;
        EY <= 2'd0;
        epoch <= 2'd0;
        cap_stage <= 2'd0;
        {trig_en, trig_e} <= 2'b00;
        trig_ch <= 2'd0;
        lost_since <= 1'b0;
        {out_ovf, vf_ovf, in_underrun, pin_fault, crc_fail} <= 5'd0;
        {sn_rstale, sn_fstale, sn_missed, sn_last, sn_ord_r, sn_ord_f} <= 24'd0;
        for (i = 0; i < 4; i = i + 1) begin
          sn_rts[i] <= 16'd0;
          sn_fts[i] <= 16'd0;
        end
        {h3_r, h3_f, h2_r, h2_f} <= 16'd0;
      end
    end
  end

  wire _unused = &{1'b0, f_n[10:0], b_lo[9:0], f_e[1]};

endmodule

