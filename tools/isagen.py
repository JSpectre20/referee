"""Generate everything that depends on the instruction encoding from isa.yaml.

isa.yaml is the single source of truth. This script writes:

  tools/isa_tables.py   opcodes, fields, operand lists, enums, aliases: the
                        tables the assembler (tools/refasm.py) and the model
                        (tools/refmodel.py) run on
  src/engine.v          the block between the GENERATED markers: Verilog
                        localparams for every opcode, field and enum
  docs/isa-timing.md    the instruction table between the GENERATED markers

    python3 tools/isagen.py           regenerate
    python3 tools/isagen.py --check   fail if any generated output is stale (CI)

It also validates the spec: unique opcodes, no use of reserved opcodes, every
operand inside [10:0], and no two operands of one instruction overlapping.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ISA = ROOT / "isa.yaml"
OUT_PY = ROOT / "tools" / "isa_tables.py"
OUT_V = ROOT / "src" / "engine.v"
OUT_MD = ROOT / "docs" / "isa-timing.md"

V_BEGIN = "  // BEGIN GENERATED by tools/isagen.py from isa.yaml -- do not edit"
V_END = "  // END GENERATED"
MD_BEGIN = "<!-- BEGIN GENERATED instruction table (tools/isagen.py) -->"
MD_END = "<!-- END GENERATED instruction table -->"


class SpecError(Exception):
    pass


def parse_operands(syntax):
    """'judge b[, raw][, push]' -> ('judge', [('b', False), ('raw', True), ('push', True)])."""
    m = re.match(r"^(\w+)\s*(.*)$", syntax)
    mnemonic, rest = m.group(1), m.group(2)
    ops = []
    for opt, name in re.findall(r"(\[\s*,?\s*)?(\w+)\]?", rest):
        ops.append((name, bool(opt)))
    return mnemonic, ops


def load():
    d = yaml.safe_load(ISA.read_text())
    fields = {k: tuple(v["bits"]) for k, v in d["fields"].items()}
    reserved = {int(k): v for k, v in (d.get("reserved_opcodes") or {}).items()}
    seen = {}
    instrs = []
    for ins in d["instructions"]:
        name, op = ins["name"], ins["opcode"]
        if op in seen:
            raise SpecError(f"opcode {op:#x} used by {seen[op]} and {name}")
        if op in reserved:
            raise SpecError(f"{name} uses reserved opcode {op:#x}")
        if not 0 <= op < 32:
            raise SpecError(f"{name}: opcode {op:#x} doesn't fit in 5 bits")
        seen[op] = name
        mnemonic, ops = parse_operands(ins["syntax"])
        used = set()
        for f, _ in ops:
            if f not in fields:
                raise SpecError(f"{name}: unknown operand {f!r}")
            hi, lo = fields[f]
            bits = set(range(lo, hi + 1))
            if hi > 10:
                raise SpecError(f"{name}: operand {f} reaches bit {hi} (opcode is [15:11])")
            if bits & used:
                raise SpecError(f"{name}: operand {f} overlaps another operand")
            used |= bits
        instrs.append(
            {
                "name": name,
                "mnemonic": mnemonic,
                "opcode": op,
                "operands": ops,
                "cycles": ins["cycles"],
                "waits": bool(ins.get("waits", False)),
                "pad_latency": ins.get("pad_latency"),
                "syntax": ins["syntax"],
                "semantics": ins["semantics"],
            }
        )
    return d, fields, reserved, instrs


