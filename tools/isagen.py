# Generators
# ----------------------------------------------------------------------------


def gen_python(d, fields, reserved, instrs):
    lines = [
        "# GENERATED by tools/isagen.py from isa.yaml -- do not edit.",
        "# SPDX-License-Identifier: Apache-2.0",
        '"""Encoding tables for the Referee engine ISA (see isa.yaml)."""',
        "",
        f"VERSION = {d['version']!r}",
        "OPCODE_SHIFT = 11",
        "",
        "# field name -> (msb, lsb)",
        "FIELDS = {",
    ]
    lines += [f"    {k!r}: {v!r}," for k, v in fields.items()]
    lines += ["}", "", "# mnemonic -> spec", "INSTR = {"]
    for i in instrs:
        lines.append(
            f"    {i['mnemonic']!r}: {{'name': {i['name']!r}, 'opcode': {i['opcode']:#04x}, "
            f"'operands': {i['operands']!r}, 'cycles': {i['cycles']}, 'waits': {i['waits']}}},"
        )
    lines += ["}", "", "OPCODES = {v['opcode']: k for k, v in INSTR.items()}", ""]
    lines.append(f"ENUMS = {d['enums']!r}")
    lines.append(f"FLAG_KEYWORDS = {d['flags_kw']!r}")
    lines.append(f"ALIASES = {d['aliases']!r}")
    lines.append(f"RESERVED_OPCODES = {sorted(reserved)!r}")
    return "\n".join(lines) + "\n"


def gen_verilog(d, fields, instrs):
    out = [V_BEGIN, "  /* verilator lint_off UNUSEDPARAM */"]
    for i in instrs:
        out.append(f"  localparam [4:0] OP_{i['name']:<6} = 5'h{i['opcode']:02x};")
    for k, (hi, lo) in fields.items():
        out.append(f"  localparam integer F_{k.upper()}_HI = {hi}, F_{k.upper()}_LO = {lo};")
    for enum, vals in d["enums"].items():
        width = max(1, max(vals.values()).bit_length())
        for name, v in vals.items():
            out.append(f"  localparam [{width - 1}:0] {enum.upper()}_{name.upper()} = {width}'d{v};")
    out.append("  /* verilator lint_on UNUSEDPARAM */")
    out.append(V_END)
    return "\n".join(out)


def gen_table(instrs, reserved):
    rows = [
        "| Opcode | Syntax | Cycles | Effect |",
        "| --- | --- | --- | --- |",
    ]
    for i in instrs:
        cyc = "≥ 1 (waits)" if i["waits"] else str(i["cycles"])
        sem = i["semantics"].replace("|", "\\|")
        rows.append(f"| {i['opcode']:#04x} | `{i['syntax']}` | {cyc} | {sem} |")
    if reserved:
        rows.append(f"| {min(reserved):#04x}..{max(reserved):#04x} | reserved | - | {next(iter(reserved.values()))} |")
    return "\n".join([MD_BEGIN, *rows, MD_END])


def splice(text, begin, end, block):
    """Replace the block between the begin/end markers (inclusive) with `block`."""
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < 0:
        raise SpecError(f"markers not found: {begin!r}")
    return text[:i] + block + text[j + len(end):]


def outputs():
    d, fields, reserved, instrs = load()
    res = {OUT_PY: gen_python(d, fields, reserved, instrs)}
    if OUT_V.exists():
        res[OUT_V] = splice(OUT_V.read_text(), V_BEGIN, V_END, gen_verilog(d, fields, instrs))
    res[OUT_MD] = splice(OUT_MD.read_text(), MD_BEGIN, MD_END, gen_table(instrs, reserved))
    return res


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated output is stale")
    args = ap.parse_args(argv)
    try:
        res = outputs()
    except SpecError as e:
        sys.exit(f"isa.yaml: {e}")
    stale = [p for p, text in res.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale:
            sys.exit("stale generated files (run tools/isagen.py): " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print("generated files are up to date")
        return
    for p in stale:
        p.write_text(res[p])
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
